class JobWorker(QObject):
    progress = Signal(str)
    succeeded = Signal(object)
    failed = Signal(str)
    cancelled = Signal()
    finished = Signal()

    def __init__(self, operation: Callable, cancel: threading.Event):
        super().__init__()
        self.operation = operation
        self.cancel = cancel

    @Slot()
    def run(self) -> None:
        try:
            result = self.operation(self.progress.emit, self.cancel.is_set)
            if self.cancel.is_set():
                self.cancelled.emit()
            else:
                self.succeeded.emit(result)
        except ReviewCancelled:
            self.cancelled.emit()
        except Exception as exc:
            # These errors are generated by our validation, without provider payloads.
            if isinstance(exc, ReviewError):
                message = str(exc)
            else:
                name = type(exc).__name__
                advice = {
                    "AuthenticationError": "The API key was rejected. Check the key and account.",
                    "PermissionDeniedError": "Your API account cannot access this model. Choose an available model.",
                    "NotFoundError": "The model was not found. Check the model ID and account access.",
                    "RateLimitError": "The provider rate limit or account quota was reached. Check billing or try later.",
                    "APIConnectionError": "Could not connect to OpenAI. Check your connection and proxy configuration.",
                    "APITimeoutError": "The API request timed out. Try again when the connection is stable.",
                    "BadRequestError": "OpenAI rejected the request. Check that this model supports the configured API.",
                }.get(name, "Check the API configuration, network connection, and local disk permissions.")
                message = f"{name}: {advice}"
            self.failed.emit(message)
        finally:
            # Release the closure's references to the window before QObject disposal.
            self.operation = None
            self.finished.emit()


class MetadataDialog(QDialog):
    def __init__(self, paper: dict, parent: QWidget):
        super().__init__(parent)
        self.setWindowTitle("Paper metadata")
        self.resize(520, 300)
        form = QFormLayout(self)
        self.title = QLineEdit(paper["title"])
        self.title.setObjectName("metadataTitle")
        self.authors = QLineEdit(paper["authors"] or "")
        self.year = QSpinBox()
        self.year.setRange(0, 9999)
        self.year.setSpecialValueText("Unknown")
        self.year.setValue(paper["year"] or 0)
        self.doi = QLineEdit(paper["doi"] or "")
        self.status = QComboBox()
        self.status.addItems(["Unread", "In Progress", "Reviewed"])
        self.status.setCurrentText(paper["status"])
        self.checked = QCheckBox("Read / verified")
        self.checked.setChecked(paper["checked"])
        for label, widget in (("Title", self.title), ("Authors", self.authors), ("Year", self.year),
                              ("DOI", self.doi), ("Status", self.status), ("Check", self.checked)):
            form.addRow(label, widget)
        buttons = QDialogButtonBox(QDialogButtonBox.StandardButton.Save | QDialogButtonBox.StandardButton.Cancel)
        buttons.accepted.connect(self.accept)
        buttons.rejected.connect(self.reject)
        form.addRow(buttons)

    def accept(self) -> None:
        if not self.title.text().strip():
            QMessageBox.warning(self, "Title required", "Enter a title for this paper.")
            return
        if self.year.value() and self.year.value() < 1000:
            QMessageBox.warning(self, "Invalid year", "Use a four-digit year, or 0 for Unknown.")
            return
        super().accept()


