class SafeBrowser(QTextBrowser):
    """Markdown may contain links/images; never fetch document resources."""

    def __init__(self, parent: QWidget | None = None):
        super().__init__(parent)
        self.setOpenLinks(False)
        self.setOpenExternalLinks(False)
        self.anchorClicked.connect(self._open_link)

    def loadResource(self, resource_type: int, url: QUrl):  # noqa: N802 (Qt API)
        return QByteArray()

    def _open_link(self, url: QUrl) -> None:
        if url.scheme() not in ("https", "http"):
            return
        choice = QMessageBox.question(
            self, "Open external link?", f"Open this address in your browser?\n\n{url.toDisplayString()}",
            QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
            QMessageBox.StandardButton.No,
        )
        if choice == QMessageBox.StandardButton.Yes:
            QDesktopServices.openUrl(url)


