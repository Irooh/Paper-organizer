    def _paper_id_at(self, row: int) -> int | None:
        item = self.table.item(row, 0)
        return item.data(Qt.ItemDataRole.UserRole) if item else None

    def _refresh_table(self, preferred_id: int | None = None, *, reload_paper: bool = False) -> None:
        if not self._save_notes():
            return
        selected = preferred_id if preferred_id is not None else self._active_id
        try:
            papers = self.db.list_papers(self.search.text().strip())
        except Exception as exc:
            self._error("Could not load library", str(exc))
            return
        self._refreshing = True
        self.table.setSortingEnabled(False)
        with QSignalBlocker(self.table):
            self.table.setRowCount(len(papers))
            selected_row = -1
            for row, paper in enumerate(papers):
                values = ["", paper["title"], paper["authors"] or "", str(paper["year"] or ""),
                          paper["doi"] or "", paper["status"], str(paper["id"])]
                for column, value in enumerate(values):
                    item = QTableWidgetItem(value)
                    item.setData(Qt.ItemDataRole.UserRole, paper["id"])
                    item.setToolTip(value)
                    if column == 0:
                        item.setFlags(Qt.ItemFlag.ItemIsEnabled | Qt.ItemFlag.ItemIsSelectable | Qt.ItemFlag.ItemIsUserCheckable)
                        item.setCheckState(Qt.CheckState.Checked if paper["checked"] else Qt.CheckState.Unchecked)
                    self.table.setItem(row, column, item)
                if paper["id"] == selected:
                    selected_row = row
            if selected_row < 0 and papers:
                selected_row = 0
            if selected_row >= 0:
                self.table.selectRow(selected_row)
            else:
                self.table.clearSelection()
        self._refreshing = False
        self.library_count.setText(f"LIBRARY · {len(papers)} paper{'s' if len(papers) != 1 else ''}")
        if reload_paper:
            rows = self.table.selectionModel().selectedRows()
            self._load_paper(self._paper_id_at(rows[0].row()) if rows else None)
        else:
            self._selection_changed()

    def _selection_changed(self) -> None:
        if self._refreshing:
            return
        rows = self.table.selectionModel().selectedRows()
        paper_id = self._paper_id_at(rows[0].row()) if rows else None
        if paper_id == self._active_id and paper_id is not None:
            return
        if not self._save_notes():
            with QSignalBlocker(self.table):
                for row in range(self.table.rowCount()):
                    if self._paper_id_at(row) == self._active_id:
                        self.table.selectRow(row)
                        break
            return
        self._load_paper(paper_id)

    def _load_paper(self, paper_id: int | None) -> None:
        try:
            paper = self.db.get_paper(paper_id) if paper_id is not None else None
        except Exception as exc:
            self._error("Could not load paper", str(exc))
            return
        self._active_id = paper["id"] if paper else None
        self._note_paper_id = self._active_id
        self._loading_notes = True
        self._notes_dirty = False
        self._notes_timer.stop()
        if paper:
            self.paper_title.setTextFormat(Qt.TextFormat.PlainText)
            self.paper_title.setText(paper["title"])
            meta = " · ".join(str(value) for value in (paper["authors"], paper["year"], paper["doi"], paper["status"]) if value)
            self.paper_meta.setTextFormat(Qt.TextFormat.PlainText)
            self.paper_meta.setText(meta or "Add bibliographic details with Edit metadata.")
            self.reader.setPlainText("\n\n".join(f"── Page {i} ──\n\n{text}" for i, text in enumerate(paper["pages"], 1)))
            self.notes.setHtml(paper["notes_html"] or "")
        else:
            self.paper_title.setText("Select a paper")
            self.paper_meta.setText("Import a PDF to build your library.")
            self.reader.clear()
            self.notes.clear()
        self.notes.setEnabled(paper is not None)
        self.notes_status.setText("NOTES · autosaved")
        self._loading_notes = False
        self._refresh_reviews()
        self._update_buttons()

    def _checked_changed(self, item: QTableWidgetItem) -> None:
        if self._refreshing or item.column() != 0:
            return
        paper_id = item.data(Qt.ItemDataRole.UserRole)
        try:
            self.db.set_checked(paper_id, item.checkState() == Qt.CheckState.Checked)
        except Exception as exc:
            self._error("Could not update check", str(exc))
            self._refresh_table()

    def _notes_changed(self) -> None:
        if self._loading_notes or self._note_paper_id is None:
            return
        self._notes_dirty = True
        self.notes_status.setText("NOTES · saving…")
        self._notes_timer.start()

    def _save_notes(self) -> bool:
        if not self._notes_dirty or self._note_paper_id is None:
            return True
        self._notes_timer.stop()
        try:
            self.db.save_notes(self._note_paper_id, self.notes.toHtml())
        except Exception as exc:
            self.notes_status.setText("NOTES · save failed; changes remain in this window")
            self._error("Could not save notes", str(exc))
            return False
        self._notes_dirty = False
        self.notes_status.setText("NOTES · saved")
        return True

    def _toggle_bold(self) -> None:
        self.notes.setFontWeight(QFont.Weight.Normal if self.notes.fontWeight() >= QFont.Weight.Bold else QFont.Weight.Bold)
        self.notes.setFocus()

    def _toggle_italic(self) -> None:
        self.notes.setFontItalic(not self.notes.fontItalic())
        self.notes.setFocus()

    def _insert_bullets(self) -> None:
        cursor = self.notes.textCursor()
        cursor.beginEditBlock()
        current = cursor.currentList()
        if current:
            block = cursor.blockFormat()
            block.setObjectIndex(-1)
            cursor.setBlockFormat(block)
        else:
            fmt = QTextListFormat()
            fmt.setStyle(QTextListFormat.Style.ListDisc)
            cursor.createList(fmt)
        cursor.endEditBlock()
        self.notes.setTextCursor(cursor)
        self.notes.setFocus()

    def _edit_metadata(self) -> None:
        if self._thread is not None or self._active_id is None or not self._save_notes():
            return
        try:
            paper = self.db.get_paper(self._active_id)
            if not paper:
                return
            dialog = MetadataDialog(paper, self)
            if dialog.exec() != QDialog.DialogCode.Accepted:
                return
            self.db.update_metadata(paper["id"], dialog.title.text().strip(), dialog.authors.text().strip(),
                                    dialog.year.value() or None, dialog.doi.text().strip(),
                                    dialog.status.currentText(), dialog.checked.isChecked())
            self._refresh_table(paper["id"], reload_paper=True)
        except Exception as exc:
            self._error("Could not update metadata", str(exc))

    def _open_pdf(self) -> None:
        if self._active_id is None:
            return
        try:
            paper = self.db.get_paper(self._active_id)
            path = Path(paper["file_path"]) if paper else None
            if path is None or not path.is_file():
                raise FileNotFoundError("The managed PDF is missing. Re-import the original file.")
            if not QDesktopServices.openUrl(QUrl.fromLocalFile(str(path.resolve()))):
                raise OSError("No system PDF viewer could be opened.")
        except Exception as exc:
            self._error("Could not open PDF", str(exc))

    def _remove_paper(self) -> None:
        if self._active_id is None or self._thread is not None:
            return
        if QMessageBox.question(
            self, "Remove paper?", "Remove this paper, its notes, and all reviews from the library?\n\n"
            "The managed PDF copy is retained on disk. The original file is never deleted.",
            QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
            QMessageBox.StandardButton.No,
        ) != QMessageBox.StandardButton.Yes:
            return
        if not self._save_notes():
            return
        try:
            self.db.remove_paper(self._active_id)
            self._active_id = self._note_paper_id = None
            self._refresh_table()
        except Exception as exc:
            self._error("Could not remove paper", str(exc))

    def _import_pdfs(self) -> None:
        if self._thread is not None:
            return
        paths, _ = QFileDialog.getOpenFileNames(self, "Import research papers", "", "PDF documents (*.pdf)")
        if not paths:
            return

        def operation(progress, cancelled):
            imported, failures = [], []
            for number, filename in enumerate(paths, 1):
                if cancelled():
                    break
                progress(f"Importing PDF {number} of {len(paths)}…")
                try:
                    imported.append(import_pdf(Path(filename), self.db, self.pdf_dir))
                except Exception as exc:
                    failures.append(f"{Path(filename).name}: {exc}")
            return imported, failures

        self._start_job(operation, self._import_completed)

    def _import_completed(self, result) -> None:
        imported, failures = result
        self.search.clear()
        self._refresh_table(imported[-1] if imported else None)
        self.task_status.setText(f"Imported {len(imported)} PDF(s). Duplicate files reuse their library entry.")
        if failures:
            self._error("Some PDFs could not be imported", "\n".join(failures))

    def _run_review(self) -> None:
        if self._active_id is None or self._thread is not None or not self._save_notes():
            return
        key = self.api_key.text().strip() or os.environ.get("OPENAI_API_KEY", "")
        if not key:
            QMessageBox.information(self, "API key required", "Enter an OpenAI API key in the password field or set OPENAI_API_KEY before launching. Keys entered here remain in memory for this session.")
            self.api_key.setFocus()
            return
        model = self.model.text().strip()
        if not model:
            QMessageBox.information(self, "Model required", "Enter an OpenAI model ID available to your API account.")
            return
        try:
            paper = self.db.get_paper(self._active_id)
        except Exception as exc:
            self._error("Could not load paper", str(exc))
            return
        if not paper:
            return
        paper_id = paper["id"]
        settings = ReviewSettings(model=model, rounds=self.rounds.value())

        def operation(progress, cancelled):
            engine = StormEngine(api_key=key, settings=settings)
            try:
                markdown = engine.review(pages=paper["pages"], title=paper["title"], progress=progress, cancelled=cancelled)
                return paper_id, markdown, model
            finally:
                engine.close()

        self.tabs.setCurrentIndex(1)
        self._start_job(operation, self._review_completed)

    def _review_completed(self, result) -> None:
        paper_id, markdown, model = result
        try:
            self.db.add_review(paper_id, markdown, model)
            self._refresh_table(self._active_id, reload_paper=True)
            self.task_status.setText("Review saved. Check the cited paper passages before relying on the findings.")
        except Exception as exc:
            # Preserve the generated result even if a transient storage problem occurs.
            self._review_markdown = markdown
            self.review.setMarkdown(markdown)
            self.export_button.setEnabled(True)
            self._error("Review generated but could not be saved", f"{exc}\n\nThe result is visible; export it before switching papers or closing.")

    def _refresh_reviews(self) -> None:
        with QSignalBlocker(self.review_history):
            self.review_history.clear()
            if self._active_id is not None:
                try:
                    for review in self.db.list_reviews(self._active_id):
                        self.review_history.addItem(f"{review['created_at']} · {review['model']} · #{review['id']}", review["markdown"])
                except Exception as exc:
                    self._error("Could not load reviews", str(exc))
            self.review_history.setCurrentIndex(0 if self.review_history.count() else -1)
        self._show_review()

    def _show_review(self, _index: int = -1) -> None:
        self._review_markdown = self.review_history.currentData() or ""
        self.review.setMarkdown(self._review_markdown)
        self.export_button.setEnabled(bool(self._review_markdown))

    def _export_review(self) -> None:
        if not self._review_markdown:
            return
        filename, _ = QFileDialog.getSaveFileName(self, "Export review", "paper-review.md", "Markdown (*.md)")
        if filename:
            try:
                Path(filename).write_text(self._review_markdown, encoding="utf-8")
                self.statusBar().showMessage("Markdown review exported.", 5000)
            except OSError as exc:
                self._error("Could not export review", str(exc))

    def _start_job(self, operation: Callable, completed: Callable) -> None:
        if self._thread is not None:
            return
        # CPython can collect cycles on whichever thread happens to allocate next.
        # PySide widget wrappers must be finalized on the GUI thread. Pause automatic
        # collection during this app's single worker, then collect here on completion.
        self._gc_was_enabled = gc.isenabled()
        gc.collect()
        gc.disable()
        try:
            self._cancel = threading.Event()
            self._thread = QThread(self)
            self._worker = JobWorker(operation, self._cancel)
            self._worker.moveToThread(self._thread)
            self._thread.started.connect(self._worker.run)
            self._worker.progress.connect(self.task_status.setText)
            self._worker.succeeded.connect(completed)
            self._worker.failed.connect(self._job_failed)
            self._worker.cancelled.connect(self._job_cancelled)
            self._worker.finished.connect(self._thread.quit)
            self._worker.finished.connect(self._worker.deleteLater)
            self._thread.finished.connect(self._job_finished)
            self._thread.finished.connect(self._thread.deleteLater)
            self.task_status.setText("Starting task…")
            self._update_buttons()
            self._thread.start()
        except Exception as exc:
            if self._worker is not None:
                self._worker.deleteLater()
            if self._thread is not None:
                self._thread.deleteLater()
            self._worker = None
            self._thread = None
            self._restore_gc()
            self._update_buttons()
            self._error("Could not start task", type(exc).__name__)

    def _restore_gc(self) -> None:
        previous = self._gc_was_enabled
        self._gc_was_enabled = None
        if previous:
            gc.enable()
            gc.collect()

    def _update_buttons(self) -> None:
        selected = self._active_id is not None
        busy = self._thread is not None
        self.import_button.setEnabled(not busy)
        self.metadata_button.setEnabled(selected and not busy)
        self.remove_button.setEnabled(selected and not busy)
        self.open_button.setEnabled(selected)
        self.run_button.setEnabled(selected and not busy)
        self.cancel_button.setVisible(busy)
        self.cancel_button.setEnabled(busy and not self._cancel.is_set())
        self.api_key.setEnabled(not busy)
        self.model.setEnabled(not busy)
        self.rounds.setEnabled(not busy)

    def _cancel_job(self) -> None:
        if self._thread is None:
            return
        self._cancel.set()
        self.cancel_button.setEnabled(False)
        self.task_status.setText("Cancellation requested. Waiting for the current PDF/API operation to finish…")

    def _job_failed(self, message: str) -> None:
        self.task_status.setText("Task failed. See the error dialog for recovery steps.")
        self._error("Task failed", f"{message}\n\nYour stored papers, notes, and previous reviews are unchanged. "
                    "Provider request details are omitted to protect credentials.")

    def _job_cancelled(self) -> None:
        self.task_status.setText("Task cancelled. Any PDFs already imported remain in the library.")
        self._refresh_table()

    @Slot()
    def _job_finished(self) -> None:
        self._worker = None
        self._thread = None
        self._restore_gc()
        self._update_buttons()
        if self._close_pending:
            self._close_pending = False
            self.close()

    def _error(self, title: str, message: str) -> None:
        box = QMessageBox(self)
        box.setIcon(QMessageBox.Icon.Warning)
        box.setWindowTitle(title)
        box.setTextFormat(Qt.TextFormat.PlainText)
        box.setText(message)
        box.exec()

    def closeEvent(self, event: QCloseEvent) -> None:  # noqa: N802
        if not self._save_notes():
            event.ignore()
            return
        if self._thread is not None:
            if not self._close_pending:
                choice = QMessageBox.question(
                    self, "Task running", "Cancel the background task and close after it finishes?",
                    QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
                    QMessageBox.StandardButton.No,
                )
                if choice == QMessageBox.StandardButton.Yes:
                    # The modal dialog runs an event loop: the worker may have
                    # finished and cleared its references while it was open.
                    if self._thread is None:
                        self._close_pending = False
                        self.api_key.clear()
                        event.accept()
                        return
                    self._close_pending = True
                    self._cancel_job()
            event.ignore()
            return
        self.api_key.clear()
        event.accept()
